begin;
create extension if not exists pgtap with schema extensions;
select no_plan();
create function pg_temp.vs(n integer) returns uuid language sql immutable as
 $$select md5('visit-state-' || n)::uuid$$;
select has_function('public','set_visit_status',array['uuid','public.visit_status','text'],'state RPC exists');
insert into auth.users(id,email) select pg_temp.vs(n),'vs-'||n||'@example.invalid' from generate_series(1,5)n;
insert into public.profiles(id,role,display_name,is_active) values
 (pg_temp.vs(1),'owner','Owner',true),(pg_temp.vs(2),'admin','Admin',true),
 (pg_temp.vs(3),'seller','Seller',true),(pg_temp.vs(4),'seller','Other',true),
 (pg_temp.vs(5),'seller','Inactive',false);
insert into public.vehicles(id,brand,model,year) values(pg_temp.vs(20),'Test','Visit',2024);
insert into public.contacts(id,normalized_phone,display_name) values(pg_temp.vs(10),'+5491177000031','Customer');
insert into public.inquiries(id,submission_id,contact_id,originating_vehicle_id,assignee_id,submitted_name,submitted_phone)
 values(pg_temp.vs(30),pg_temp.vs(31),pg_temp.vs(10),pg_temp.vs(20),pg_temp.vs(3),'Customer','+5491177000031');
insert into public.inquiry_interests(inquiry_id,vehicle_id) values(pg_temp.vs(30),pg_temp.vs(20));
insert into public.visits(id,inquiry_id,vehicle_id,scheduled_at,request_assignee_id,purpose)
 values(pg_temp.vs(40),pg_temp.vs(30),pg_temp.vs(20),clock_timestamp()-interval '1 hour',pg_temp.vs(3),'Keep purpose');
set local role authenticated;
select set_config('request.jwt.claim.sub',pg_temp.vs(3)::text,true);
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'attended')$$,'22023','invalid visit transition','Requested cannot record attendance');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'confirmed')$$,'late initial confirmation allowed without opening schedule');
select is((select status::text from public.visits),'confirmed','confirmation persisted');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'attended')$$,'confirmed past appointment accepts attendance');
select is((select outcome_assignee_id from public.visits),pg_temp.vs(3),'first outcome credits inquiry assignee');
select ok((select first_outcome_recorded_at is not null from public.visits),'first outcome recorded');
select is((select count(*)::int from public.visit_history),2,'each transition appends history');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'attended')$$,'same-state retry is a no-op');
select is((select count(*)::int from public.visit_history),2,'no-op adds no history');
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'no_show','  ')$$,'22023','correction reason is required','final correction needs nonblank reason');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'no_show','Correct result')$$,'seller corrects final outcome');
select is((select reason from public.visit_history order by occurred_at desc,id desc limit 1),'Correct result','reason retained');
select set_config('request.jwt.claim.sub',pg_temp.vs(4)::text,true);
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'no_show')$$,'42501','visit access denied','unrelated seller denied even for no-op');
select set_config('request.jwt.claim.sub',pg_temp.vs(5)::text,true);
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'cancelled','Correction')$$,'42501','visit access denied','inactive seller denied');
select set_config('request.jwt.claim.sub',pg_temp.vs(2)::text,true);
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'confirmed','Restore')$$,'admin restores past Confirmed');
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'requested')$$,'22023','invalid visit transition','state-only downgrade is not rescheduling');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'cancelled')$$,'pending visit can cancel');
reset role;
create temp table original_outcome as select first_outcome_recorded_at,outcome_assignee_id from public.visits;
update public.inquiries set status='closed_without_sale',assignee_id=null where id=pg_temp.vs(30);
update public.vehicles set availability_status='sold',sale_enabled=false where id=pg_temp.vs(20);
set local role authenticated;
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'attended','Historical correction')$$,'final correction survives closure and Sold/blocked vehicle');
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'confirmed','Restore')$$,'22023','inquiry is not active','reactivation requires active inquiry');
reset role;
update public.inquiries set status='following_up' where id=pg_temp.vs(30);
set local role authenticated;
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'confirmed','Restore')$$,'22023','vehicle does not accept visits','reactivation requires eligible vehicle');
reset role;
update public.vehicles set availability_status='reserved',sale_enabled=true where id=pg_temp.vs(20);
set local role authenticated;
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'requested','Restore proposal')$$,'final state may restore Requested');
select lives_ok($$select public.set_visit_status(pg_temp.vs(40),'cancelled')$$,'Requested cancellation allowed');
reset role;
insert into public.visits(id,inquiry_id,vehicle_id,scheduled_at) values
 (pg_temp.vs(41),pg_temp.vs(30),pg_temp.vs(20),clock_timestamp()+interval '1 day');
set local role authenticated;
select throws_ok($$select public.set_visit_status(pg_temp.vs(40),'confirmed','Restore')$$,'22023','inquiry already has a pending visit','another pending visit blocks restoration');
select lives_ok($$select public.set_visit_status(pg_temp.vs(41),'confirmed')$$,'future visit can confirm');
select throws_ok($$select public.set_visit_status(pg_temp.vs(41),'no_show')$$,'22023','visit time has not been reached','No-show requires reached time');
select throws_ok($$select public.set_visit_status(pg_temp.vs(41),'attended')$$,'22023','visit time has not been reached','attendance requires reached time');
select lives_ok($$select public.set_visit_status(pg_temp.vs(41),'cancelled')$$,'admin records unassigned cancellation');
reset role;
update public.inquiries set assignee_id=pg_temp.vs(4) where id=pg_temp.vs(30);
set local role authenticated;
select lives_ok($$select public.set_visit_status(pg_temp.vs(41),'confirmed','Restore')$$,'unassigned outcome reactivates');
select lives_ok($$select public.set_visit_status(pg_temp.vs(41),'cancelled')$$,'reactivated visit finalizes');
reset role;
select ok((select first_outcome_recorded_at is not null and outcome_assignee_id is null from public.visits where id=pg_temp.vs(41)),'recorded unassigned attribution stays null after reassignment');
select is((select first_outcome_recorded_at from public.visits where id=pg_temp.vs(40)),(select first_outcome_recorded_at from original_outcome),'first outcome timestamp never overwritten');
select is((select outcome_assignee_id from public.visits where id=pg_temp.vs(40)),pg_temp.vs(3),'first attribution never overwritten');
select is((select purpose from public.visits where id=pg_temp.vs(40)),'Keep purpose','purpose unchanged');
select is((select count(*)::int from public.reservations),0,'no reservation effects');
select is((select count(*)::int from public.vehicle_inquiry_rotation),0,'no routing effects');
select ok(not has_function_privilege('anon','public.set_visit_status(uuid,public.visit_status,text)','execute'),'anonymous execution denied');
select ok(not has_function_privilege('service_role','public.set_visit_status(uuid,public.visit_status,text)','execute'),'service execution denied');
select ok(not has_function_privilege('authenticated','public.lock_managed_visit(uuid)','execute'),'internal lock helper is not callable');
update public.visits set status='confirmed',scheduled_at=clock_timestamp()-interval '1 second' where id=pg_temp.vs(41);
set local role authenticated;
select set_config('request.jwt.claim.sub',pg_temp.vs(1)::text,true);
select lives_ok($$select public.set_visit_status(pg_temp.vs(41),'no_show')$$,'Owner records reached-time No-show');
select is((select status::text from public.visits where id=pg_temp.vs(41)),'no_show','No-show persisted');
select throws_ok($$select public.set_visit_status(null,'confirmed')$$,'42501','visit access denied','missing visit is privacy-safe denial');
select throws_ok($$select public.set_visit_status(pg_temp.vs(41),null)$$,'22023','invalid visit transition','null state rejected');
select set_config('request.jwt.claim.sub',pg_temp.vs(3)::text,true);
select throws_ok($$select public.set_visit_status(pg_temp.vs(41),'cancelled','Correction')$$,'42501','visit access denied','former assignee cannot correct');
reset role;
select ok(not exists(select 1 from public.visit_history where previous_scheduled_at is distinct from scheduled_at),'state changes never move appointments');
select * from finish();
rollback;
